-- Features needed by the React storefront: product images/sizes/sub-category/bestseller,
-- cart and order lines per size, address book, wishlist, payment method/status on orders.

-- Catalog
ALTER TABLE products ADD COLUMN sub_category VARCHAR(100);
ALTER TABLE products ADD COLUMN sizes VARCHAR(100);
ALTER TABLE products ADD COLUMN bestseller BOOLEAN DEFAULT FALSE NOT NULL;
CREATE TABLE product_images (
    product_id  BIGINT       NOT NULL REFERENCES products (id),
    position    INTEGER      NOT NULL,
    url         VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, position)
);

-- Cart / order lines per size ('' = product without sizes)
ALTER TABLE cart_items ADD COLUMN size VARCHAR(10) DEFAULT '' NOT NULL;
ALTER TABLE cart_items DROP CONSTRAINT uk_cart_user_product;
ALTER TABLE cart_items ADD CONSTRAINT uk_cart_user_product_size UNIQUE (user_id, product_id, size);
ALTER TABLE order_items ADD COLUMN size VARCHAR(10) DEFAULT '' NOT NULL;
ALTER TABLE order_items ADD COLUMN image_url VARCHAR(500);

-- Orders: how the customer pays, payment progress, recipient and notes
ALTER TABLE orders ADD COLUMN payment_method VARCHAR(10) DEFAULT 'CARD' NOT NULL;
ALTER TABLE orders ADD COLUMN payment_status VARCHAR(20) DEFAULT 'PENDING' NOT NULL;
ALTER TABLE orders ADD COLUMN recipient_name VARCHAR(120);
ALTER TABLE orders ADD COLUMN recipient_phone VARCHAR(20);
ALTER TABLE orders ADD COLUMN notes VARCHAR(500);

-- Address book (replaces the single address stored on users)
CREATE TABLE addresses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    label       VARCHAR(30),
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50),
    phone       VARCHAR(20),
    street      VARCHAR(200) NOT NULL,
    city        VARCHAR(100) NOT NULL,
    state       VARCHAR(100),
    zipcode     VARCHAR(20)  NOT NULL,
    country     VARCHAR(100) NOT NULL,
    is_default  BOOLEAN      NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);
CREATE INDEX idx_addresses_user ON addresses (user_id);
INSERT INTO addresses (user_id, label, first_name, last_name, phone, street, city, state, zipcode, country, is_default, created_at)
SELECT id, 'Home', first_name, last_name, phone, street, city, state, zipcode, country, TRUE, created_at
FROM users
WHERE street IS NOT NULL AND city IS NOT NULL AND country IS NOT NULL AND zipcode IS NOT NULL;
ALTER TABLE users DROP COLUMN street;
ALTER TABLE users DROP COLUMN city;
ALTER TABLE users DROP COLUMN state;
ALTER TABLE users DROP COLUMN country;
ALTER TABLE users DROP COLUMN zipcode;

-- Wishlist
CREATE TABLE wishlist_items (
    user_id     BIGINT    NOT NULL REFERENCES users (id),
    product_id  BIGINT    NOT NULL REFERENCES products (id),
    created_at  TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, product_id)
);
